def build_standalone_mentor_crew(
    student_profile: Dict[str, Any],
    topic: str = "General",
    study_query: Optional[str] = None,
    verified_resources: Optional[List[Dict[str, Any]]] = None,
    llm: Optional[LLM] = None,
) -> Tuple[Crew, Task]:
    """Construct a standalone Crew for the Mentor Agent."""
    mentor_agent = create_mentor_agent(llm=llm)
    task = create_standalone_mentor_task(
        agent=mentor_agent,
        student_profile=student_profile,
        topic=topic,
        study_query=study_query,
        verified_resources=verified_resources,
    )
    crew_kwargs = {
        "agents": [mentor_agent],
        "tasks": [task],
        "process": Process.sequential,
        "verbose": True,
    }
    try:
        from backend.observability import attach_crewai_callbacks
        attach_crewai_callbacks(crew_kwargs, agent_name="Mentor Agent")
    except Exception:
        pass
    crew = Crew(**crew_kwargs)
    return crew, task


def run_standalone_mentor_workflow(
    student_profile: Optional[Dict[str, Any]] = None,
    topic: str = "General",
    study_query: Optional[str] = None,
    verified_resources: Optional[List[Dict[str, Any]]] = None,
    llm: Optional[LLM] = None,
) -> Dict[str, Any]:
    """Execute standalone Mentor Agent workflow."""
    if student_profile is None:
        student_profile = {"display_name": "Student", "grade": "Class 10", "preferred_language": "English"}

    crew, task = build_standalone_mentor_crew(
        student_profile=student_profile,
        topic=topic,
        study_query=study_query,
        verified_resources=verified_resources,
        llm=llm,
    )
    result = crew.kickoff()
    raw_text = task.output.raw if (task.output and task.output.raw) else str(result.raw if hasattr(result, "raw") else result).strip()

    text = raw_text
    if "```json" in text:
        text = text.split("```json")[1].split("```")[0].strip()
    elif "```" in text:
        text = text.split("```")[1].split("```")[0].strip()

    try:
        parsed = json_repair.loads(text)
    except Exception:
        try:
            parsed = json.loads(text)
        except Exception:
            parsed = {"mentor_overview": raw_text, "recommendations": []}

    if not isinstance(parsed, dict):
        parsed = {"mentor_overview": str(parsed), "recommendations": []}

    return {
        "mentor_recommendations": parsed,
        "raw_output": raw_text,
    }

